#!/usr/bin/env node
/**
 * kit/report.mjs — generates markdown report from catalog (reads data, doesn't change anything).
 *
 * Output (default kit/dist/report.md):
 * 1. Summary issues (style, single page scene, full slot)
 * 2. Scope table: sau, number of tokens per style
 * 3. Contrast table: ink/bg, ink-soft/bg, ink-faint/bg, accent-ink/accent, ink/surface
 * 4. Debt list: ban on incomplete typography, short reference
 * 5. Door commands
 *
 * Usage:
 * node kit/report.mjs [--out kit/dist/report.md] [--quiet]*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { contrastOnSurface, contrastRatio } from './color.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STYLES_DIR = path.join(ROOT, 'styles');
const KIT = path.join(ROOT, 'kit');

const arg = (name, fallback = null) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--')
    ? process.argv[i + 1]
    : fallback;
};
const OUT = path.resolve(arg('out', path.join(KIT, 'dist', 'report.md')));
const QUIET = process.argv.includes('--quiet');
/** --check: is the dist report up to date (don't read the stale report silently).*/
const CHECK = process.argv.includes('--check');

const read = (p) => fs.readFileSync(p, 'utf8');
const readJson = (p, fallback) => (fs.existsSync(p) ? JSON.parse(read(p)) : fallback);

function tokensCss() {
  const css = read(path.join(KIT, 'tokens.css'));
  const root = {};
  const rootMatch = css.match(/:root\s*\{([\s\S]*?)\n\}/);
  if (rootMatch) for (const v of rootMatch[1].matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/gi)) root[v[1]] = v[2].trim();
  const light = {};
  for (const m of css.matchAll(/^\[data-style="([a-z0-9-]+)"\]\s*\{([\s\S]*?)^\}/gm)) {
    const vars = {};
    for (const v of m[2].matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/gi)) vars[v[1]] = v[2].trim();
    light[m[1]] = vars;
  }
  return { root, light };
}

/**
 * Family bands from a single source: kit/families.json (1-145 seamless, conflict-free).
 * Format: [first, last, name] — kit/apply-fragments.mjs validates this file.*/
const FAMILIES = (() => {
  const j = JSON.parse(fs.readFileSync(path.join(KIT, 'families.json'), 'utf8'));
  return (j.families ?? []).map((f) => [f.from, f.to, f.name]);
})();
const familyOf = (num) => FAMILIES.find(([lo, hi]) => num >= lo && num <= hi)?.[2] ?? 'Other';
const f2 = (n) => (n === null || n === undefined ? '—' : n.toFixed(2));

function main() {
  const { root, light } = tokensCss();
  const manifest = readJson(path.join(KIT, 'shots.manifest.json'), { scenes: [] });
  // Core scenes (kit/shots.core.json) held in the repo. Remaining scenes kit/.shots-cache/ (produced).
  const coreFiles = readJson(path.join(KIT, 'shots.core.json'), { files: [] }).files ?? [];
  const scenes = coreFiles.length ? coreFiles : (manifest.scenes ?? []).map((s) => s.file);
  const allTemplates = (manifest.scenes ?? []).length;
  const contrastBaseline = readJson(path.join(KIT, 'contrast-baseline.json'), {});

  const dirs = fs
    .readdirSync(STYLES_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(STYLES_DIR, d.name, 'style.md')))
    .map((d) => d.name)
    .sort((a, b) => parseInt(a, 10) - parseInt(b, 10));

  const rows = dirs.map((dirName) => {
    const slug = dirName.replace(/^\d+-/, '');
    const num = parseInt(dirName, 10);
    const t = readJson(path.join(STYLES_DIR, dirName, 'tokens.json'), null);
    const shotsDir = path.join(STYLES_DIR, dirName, 'shots');
    const shots = fs.existsSync(shotsDir) ? fs.readdirSync(shotsDir).filter((f) => f.endsWith('.png')) : [];
    const v = { ...root, ...(light[slug] ?? {}) };
    return {
      dirName,
      slug,
      num,
      name: t?.name ?? slug,
      family: familyOf(num),
      scenes: shots.length,
      tokens: Object.keys(light[slug] ?? {}).length,
      contrast: {
        body: contrastRatio(v['ink'], v['bg']),
        soft: contrastRatio(v['ink-soft'], v['bg']),
        faint: contrastRatio(v['ink-faint'], v['bg']),
        accent: contrastRatio(v['accent-ink'], v['accent']),
        onSurface: contrastOnSurface(v['ink'], v['surface'], v['bg']),
      },
      forbiddenMissing: !Array.isArray(t?.typography?.forbidden) || t.typography.forbidden.length === 0,
      refs: Array.isArray(t?.refs) ? t.refs.length : 0,
      contrastDebt: contrastBaseline[slug] ?? null,
    };
  });

  const filled = rows.reduce((n, r) => n + r.scenes, 0);
  const slots = rows.length * scenes.length;
  const contrastIssues = rows.filter((r) => (r.contrast.body ?? 9) < 4.5 || (r.contrast.accent ?? 9) < 4.5);

  const lines = [];
  lines.push('# Catalog report');
  lines.push('');
  lines.push(`Generated by: \`node kit/report.mjs\` · sources: \`kit/tokens.css\` + \`styles/*/tokens.json\` + \`kit/shots.manifest.json\``);
  lines.push('');
  lines.push('## 1 · Summary');
  lines.push('');
  lines.push('| Measure | Value |');
  lines.push('|---|---|');
  lines.push(`| Styles | ${rows.length} |`);
  lines.push(`| Scene templates (full set) | ${allTemplates} |`);
  lines.push(`| Scenes kept in the repo | ${scenes.length} (core; the rest in \`kit/.shots-cache/\`) |`);
  lines.push(`| Filled scenes | ${filled} / ${slots} (${Math.round((filled / slots) * 100)}%) |`);
  lines.push(`| Contrast errors | ${contrastIssues.length} styles |`);
  lines.push(`| Empty typography ban list | ${rows.filter((r) => r.forbiddenMissing).length} styles |`);
  lines.push('');

  lines.push('## 2 · Kapsam');
  lines.push('');
  lines.push('| # | Style | Family | Scene | Token |');
  lines.push('|---|---|---|---|---|');
  for (const r of rows) {
    lines.push(
      `| ${r.num} | [${r.name}](../styles/${r.dirName}/style.md) | ${r.family} | ${r.scenes}/${scenes.length} | ${r.tokens} |`,
    );
  }
  lines.push('');

  lines.push('## 3 · Contrast (WCAG)');
  lines.push('');
  lines.push('Thresholds: body ≥ 4.5, uppercase text ≥ 3, accent above text ≥ 4.5. `faint` is decorative (≥ 3 target, below is a warning).');
  lines.push('');
  lines.push('| Style | ink/bg | soft/bg | faint/bg | accent-ink/accent | ink/surface |');
  lines.push('|---|---|---|---|---|---|');
  for (const r of rows) {
    const flag = (v, min) => (v !== null && v < min ? ' ⚠' : '');
    lines.push(
      `| ${r.slug} | ${f2(r.contrast.body)}${flag(r.contrast.body, 4.5)} | ${f2(r.contrast.soft)}${flag(
        r.contrast.soft,
        4.5,
      )} | ${f2(r.contrast.faint)}${flag(r.contrast.faint, 3)} | ${f2(r.contrast.accent)}${flag(
        r.contrast.accent,
        4.5,
      )} | ${f2(r.contrast.onSurface)}${flag(r.contrast.onSurface, 4.5)} |`,
    );
  }
  lines.push('');

  lines.push('## 4 · Debts');
  lines.push('');
  if (rows.some((r) => r.forbiddenMissing)) {
    lines.push('### Empty `typography.forbidden`');
    lines.push('');
    lines.push(rows.filter((r) => r.forbiddenMissing).map((r) => `\`${r.slug}\``).join(' · '));
    lines.push('');
  }
  if (rows.filter((r) => r.refs < 3).length) {
    lines.push('### 3’ten az referans');
    lines.push('');
    lines.push(rows.filter((r) => r.refs < 3).map((r) => `\`${r.slug}\` (${r.refs})`).join(' · '));
    lines.push('');
  }
  if (!rows.some((r) => r.forbiddenMissing) && !rows.filter((r) => r.refs < 3).length) {
    lines.push('No debt.');
    lines.push('');
  }

  lines.push('## 5 · Doors');
  lines.push('');
  lines.push('```bash');
  lines.push('bash kit/gates.sh # all in order');
  lines.push('node kit/check-schema.mjs # schema + triplicate parity + neighbor/refs');
  lines.push('node kit/check-contrast.mjs # WCAG measurement');
  lines.push('node kit/export-tokens.mjs --check # dist is up to date');
  lines.push('node kit/build-gallery.mjs --check # catalog + gallery');
  lines.push('```');
  lines.push('');

  const md = lines.join('\n');

  if (CHECK) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (current === null) {
      console.log(`× no report: ${path.relative(ROOT, OUT)} — node kit/report.mjs`);
      return 1;
    }
    if (current !== md) {
      console.log(`× report is stale: ${path.relative(ROOT, OUT)} — refresh it with node kit/report.mjs`);
      return 1;
    }
    if (!QUIET) console.log(`✓ report is up to date: ${path.relative(ROOT, OUT)} (${rows.length} styles · ${filled}/${slots} scenes)`);
    return 0;
  }

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, md);
  if (!QUIET) {
    console.log(
      `report: ${path.relative(ROOT, OUT)} · ${rows.length} styles · ${filled}/${slots} single-page images`,
    );
  }
  return 0;
}

process.exit(main());
